"""JSON schemas for the messages that flow through the pipeline.

Step types:

    LOCAL
        Perform an action independently.

    ASK_HELP
        Request another robot to perform a task.

    HELP
        Perform a task requested by another robot.

    RECEIVE
        Receive a physical item from another robot.

    PASS
        Provide/pass a physical item to another robot.

Collaboration pairings:

    ASK_HELP <-> HELP
    RECEIVE  <-> PASS

The `target` field is only a non-binding preferred target.
The Auction and Graph Reasoning stages determine the final collaboration relation.
"""

from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field, model_validator


# ---------------------------------------------------------------------------
# Step types
# ---------------------------------------------------------------------------

StepType = Literal[
    "LOCAL",
    "ASK_HELP",
    "HELP",
    "RECEIVE",
    "PASS",
]

Kind = Literal["item", "task"]


# ---------------------------------------------------------------------------
# Input
# ---------------------------------------------------------------------------

class AgentInput(BaseModel):
    """What one robot receives.

    Raw images and hidden information remain private to the robot.
    Only structured Offer / LocalPlan information is broadcast.
    """

    task: str

    capability: str

    images: list[str] = Field(
        default_factory=list
    )

    hidden_info: list[str] = Field(
        default_factory=list
    )


class TaskConfig(BaseModel):
    """One shared-task scenario.

    Example:
        {
            "task": "...",
            "agents": [
                {
                    "capability": "...",
                    "images": [...],
                    "hidden_info": [...]
                }
            ]
        }
    """

    task: str

    agents: list[dict]

    def agent_inputs(self) -> dict[str, AgentInput]:
        return {
            f"agent_{i}": AgentInput(
                task=self.task,
                **a,
            )
            for i, a in enumerate(
                self.agents,
                start=1,
            )
        }


# ---------------------------------------------------------------------------
# Offer
# ---------------------------------------------------------------------------

class OfferNeed(BaseModel):
    """A need declared in an Offer.

    `kind="task"`:
        The robot needs another robot to perform a task.

    `kind="item"`:
        The robot needs another robot to provide an item.
    """

    kind: Kind

    text: str


class RawOffer(BaseModel):
    """What the Offer-generation LLM writes."""

    capability: str

    obs_scope: list[str] = Field(
        default_factory=list
    )

    can_do: list[str] = Field(
        default_factory=list
    )

    cannot_do: list[str] = Field(
        default_factory=list
    )

    can_provide: list[str] = Field(
        default_factory=list
    )

    needs: list[OfferNeed] = Field(
        default_factory=list
    )


class Offer(RawOffer):
    """Broadcast Offer.

    `agent` is assigned by code, not by the LLM.
    """

    agent: str


# ---------------------------------------------------------------------------
# Local Plan
# ---------------------------------------------------------------------------

class RawStep(BaseModel):
    """One local-plan step generated by the LLM."""

    type: StepType

    action: str = Field(
        min_length=1
    )

    kind: Optional[Kind] = None

    item: Optional[str] = None

    target: Optional[str] = None
    # Preferred target only.
    # Final assignment is determined later by Auction / Graph Reasoning.

    @model_validator(mode="after")
    def _validate_step(self):
        # ---------------------------------------------------------------
        # LOCAL
        # ---------------------------------------------------------------
        if self.type == "LOCAL":

            # LOCAL does not represent collaboration.
            self.kind = None
            self.item = None
            self.target = None

            return self

        # ---------------------------------------------------------------
        # ASK_HELP / HELP
        # ---------------------------------------------------------------
        if self.type in {
            "ASK_HELP",
            "HELP",
        }:

            # These are task-level collaboration relations.
            if self.kind is None:
                self.kind = "task"

            if self.kind != "task":
                raise ValueError(
                    f"{self.type} must use kind='task': "
                    f"{self.action!r}"
                )

            # No physical item is associated with task-level help.
            self.item = None

            return self

        # ---------------------------------------------------------------
        # RECEIVE / PASS
        # ---------------------------------------------------------------
        if self.type in {
            "RECEIVE",
            "PASS",
        }:

            # These are physical item-transfer relations.
            if self.kind is None:
                self.kind = "item"

            if self.kind != "item":
                raise ValueError(
                    f"{self.type} must use kind='item': "
                    f"{self.action!r}"
                )

            if not self.item:
                raise ValueError(
                    f"{self.type} requires an item: "
                    f"{self.action!r}"
                )

            return self

        return self


class RawLocalPlan(BaseModel):
    """Raw local plan generated by one robot.

    Empty plans are valid.

    Example:
        A fixed-base kitchen robot may have no relevant action
        for a living-room-only task.
    """

    steps: list[RawStep] = Field(
        default_factory=list
    )


class Step(RawStep):
    """Validated step with code-assigned ID and order."""

    id: str

    order: int


class LocalPlan(BaseModel):
    """Validated local plan for one robot."""

    agent: str

    steps: list[Step]

    @classmethod
    def from_raw(
        cls,
        agent: str,
        raw: RawLocalPlan,
        known_agents: set[str],
    ) -> "LocalPlan":

        num = agent.split("_")[-1]

        steps: list[Step] = []

        for i, s in enumerate(
            raw.steps,
            start=1,
        ):

            data = s.model_dump()

            # -----------------------------------------------------------
            # Target is only a preferred hint.
            #
            # Remove invalid targets and self-targets.
            # -----------------------------------------------------------

            target = data.get("target")

            if (
                target is not None
                and (
                    target not in known_agents
                    or target == agent
                )
            ):
                data["target"] = None

            # -----------------------------------------------------------
            # IDs and order are assigned by code.
            # The LLM never controls these fields.
            # -----------------------------------------------------------

            steps.append(
                Step(
                    id=f"{num}-{i}",
                    order=i,
                    **data,
                )
            )

        return cls(
            agent=agent,
            steps=steps,
        )

    # -------------------------------------------------------------------
    # Collaboration steps
    # -------------------------------------------------------------------

    def collaboration_steps(self) -> list[Step]:
        return [
            s
            for s in self.steps
            if s.type != "LOCAL"
        ]

    # -------------------------------------------------------------------
    # Requests
    # -------------------------------------------------------------------

    def request_steps(self) -> list[Step]:
        """Steps that request another robot."""

        return [
            s
            for s in self.steps
            if s.type in {
                "ASK_HELP",
                "RECEIVE",
            }
        ]

    # -------------------------------------------------------------------
    # Provider steps
    # -------------------------------------------------------------------

    def provider_steps(self) -> list[Step]:
        """Steps that provide help/items to another robot."""

        return [
            s
            for s in self.steps
            if s.type in {
                "HELP",
                "PASS",
            }
        ]

    # -------------------------------------------------------------------
    # Task-level collaboration
    # -------------------------------------------------------------------

    def ask_help_steps(self) -> list[Step]:
        return [
            s
            for s in self.steps
            if s.type == "ASK_HELP"
        ]

    def help_steps(self) -> list[Step]:
        return [
            s
            for s in self.steps
            if s.type == "HELP"
        ]

    # -------------------------------------------------------------------
    # Item-level collaboration
    # -------------------------------------------------------------------

    def receive_steps(self) -> list[Step]:
        return [
            s
            for s in self.steps
            if s.type == "RECEIVE"
        ]

    def pass_steps(self) -> list[Step]:
        return [
            s
            for s in self.steps
            if s.type == "PASS"
        ]


# ---------------------------------------------------------------------------
# Utility
# ---------------------------------------------------------------------------

def agent_of(step_id: str) -> str:
    """Convert a step ID to its agent ID.

    Example:
        "3-2" -> "agent_3"
    """

    return f"agent_{step_id.split('-')[0]}"


# ---------------------------------------------------------------------------
# Debug / configuration description
# ---------------------------------------------------------------------------

def describe_config(
    config: TaskConfig,
) -> str:
    """Human-readable dump of the actual scenario sent to the LLM."""

    lines = [
        f"TASK: {config.task}",
        "",
    ]

    for i, agent in enumerate(
        config.agents,
        start=1,
    ):

        lines.append(
            f"agent_{i}"
        )

        lines.append(
            f"  capability : "
            f"{agent.get('capability', '')}"
        )

        lines.append(
            f"  images     : "
            f"{agent.get('images', [])}"
        )

        hidden = agent.get(
            "hidden_info",
            [],
        )

        lines.append(
            f"  hidden_info: "
            f"{hidden if hidden else '(none)'}"
        )

    return "\n".join(lines)
