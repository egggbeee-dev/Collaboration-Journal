# schemas.py

from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field, model_validator


StepType = Literal["LOCAL", "NEED", "PASS"]
Kind = Literal["item", "task"]


# ---------------------------------------------------------------------------
# input
# ---------------------------------------------------------------------------

class AgentInput(BaseModel):
    """What one robot receives.
    
    Private inputs never leave the agent.
    Only Offer / Plan are broadcast.
    """

    task: str
    capability: str
    images: list[str] = Field(default_factory=list)
    hidden_info: list[str] = Field(default_factory=list)


class TaskConfig(BaseModel):
    """One scenario: shared task + one entry per robot."""

    task: str
    agents: list[dict]

    def agent_inputs(self) -> dict[str, AgentInput]:
        return {
            f"agent_{i}": AgentInput(task=self.task, **a)
            for i, a in enumerate(self.agents, start=1)
        }


# ---------------------------------------------------------------------------
# offer
# ---------------------------------------------------------------------------

class ObsItem(BaseModel):
    """A concrete object/fact within the robot's observation scope."""

    object: str
    location: Optional[str] = None
    state: Optional[str] = None


class CanDoAction(BaseModel):
    """A concrete action the robot can perform."""

    action: str
    object: Optional[str] = None
    location: Optional[str] = None
    target: Optional[str] = None


class CannotDoAction(BaseModel):
    """A task-relevant action the robot cannot perform."""

    action: str
    object: Optional[str] = None
    location: Optional[str] = None
    reason: Optional[str] = None


class CanProvide(BaseModel):
    """A concrete resource or contribution the robot can provide."""

    type: Kind
    object: Optional[str] = None
    location: Optional[str] = None
    action: Optional[str] = None


class OfferNeed(BaseModel):
    """A concrete dependency required from another robot."""

    kind: Kind
    action: Optional[str] = None
    object: Optional[str] = None
    location: Optional[str] = None


class RawOffer(BaseModel):
    """Structured Offer generated by the LLM."""

    capability: str

    obs_scope: list[ObsItem] = Field(
        default_factory=list
    )

    can_do: list[CanDoAction] = Field(
        default_factory=list
    )

    cannot_do: list[CannotDoAction] = Field(
        default_factory=list
    )

    can_provide: list[CanProvide] = Field(
        default_factory=list
    )

    needs: list[OfferNeed] = Field(
        default_factory=list
    )


class Offer(RawOffer):
    """Broadcast Offer. Agent ID is added by the code."""

    agent: str


