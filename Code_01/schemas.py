class RawStep(BaseModel):
    """One step as the LLM writes it."""

    type: StepType
    action: str = Field(min_length=1)

    kind: Optional[Kind] = None
    item: Optional[str] = None
    target: Optional[str] = None

    @model_validator(mode="after")
    def _check_collab_fields(self):
        if self.type == "LOCAL":
            self.kind = self.item = self.target = None
            return self

        if self.kind is None:
            raise ValueError(
                f"{self.type} step needs 'kind' (item|task): {self.action!r}"
            )

        if self.kind == "item" and not self.item:
            raise ValueError(
                f"{self.type}/item step needs 'item': {self.action!r}"
            )

        return self


class RawLocalPlan(BaseModel):
    steps: list[RawStep] = Field(default_factory=list)


class Step(RawStep):
    id: str
    order: int


class LocalPlan(BaseModel):
    agent: str
    steps: list[Step]

    @classmethod
    def from_raw(
        cls,
        agent: str,
        raw: RawLocalPlan,
        known_agents: set[str],
    ) -> "LocalPlan":

        num = agent.split("_")[-1]

        steps: list[Step] = []

        for i, s in enumerate(raw.steps, start=1):
            data = s.model_dump()

            # target is only a hint
            if (
                data["target"] is not None
                and (
                    data["target"] not in known_agents
                    or data["target"] == agent
                )
            ):
                data["target"] = None

            steps.append(
                Step(
                    id=f"{num}-{i}",
                    order=i,
                    **data,
                )
            )

        return cls(
            agent=agent,
            steps=steps,
        )

    def collaboration_steps(self) -> list[Step]:
        return [
            s for s in self.steps
            if s.type != "LOCAL"
        ]


def agent_of(step_id: str) -> str:
    """'3-2' -> 'agent_3'"""

    return f"agent_{step_id.split('-')[0]}"
